"""Report-only reasoning benchmarks, replayed from committed VCR cassettes.

Covers four LLM-backed reasoning behaviours, each with its own set of YAML
cases (all in ``cases/`` and distinguished by ``benchmark_type``):

  - ``contextualization`` — ``UserQueryReasoner.contextualize_query``:
      judges whether the rewritten query is more precise.
  - ``expansion``         — ``UserQueryReasoner.expand_query``:
      judges sub-question relevance and coverage.
  - ``completeness``      — ``CompletenessMetric.evaluate``:
      reports the LLM-assigned completeness score for known inputs.
  - ``appropriateness``   — question generated by
      ``UserQueryReasoner.request_user_interaction``:
      judges whether it suits the target contact protocol.

Never fails on a metric regression — prints and writes scores so drift is
visible.  To record cassettes or run live, set ``OPENAI_API_KEY``.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from ..common import reasoning_runner as rr
from ..common import scoring
from ..common.cases import cassette_filename, load_reasoning_cases
from ..common.reporting import render_reasoning_table, write_detailed_log, write_json

CASES_DIR    = Path(__file__).parent / "cases"
CASSETTE_DIR = Path(__file__).parent / "cassettes"
REPORT_PATH  = Path(__file__).parent / ".reports" / "latest.json"
DETAIL_LOG   = Path(__file__).parent / ".reports" / "latest.detail.jsonl"
DEFAULT_MODEL = "gpt-4o-mini"

pytestmark = pytest.mark.vcr

_cases = {c.id: c for c in load_reasoning_cases(CASES_DIR)}
_params = list(_cases.keys())
_collected_scores: list[scoring.ReasoningCaseScore] = []
_collected_results: list[rr.ReasoningRunResult] = []


@pytest.fixture(scope="session", autouse=True)
def _print_and_write_report():
    yield
    if _collected_scores:
        from rich.console import Console
        Console().print(render_reasoning_table(_collected_scores))
        write_json(_collected_scores, REPORT_PATH)
        write_detailed_log(_collected_results, DETAIL_LOG)


_DETERMINISTIC_TYPES = {"freshness"}


@pytest.mark.parametrize("case_id", _params)
async def test_case(case_id: str) -> None:
    case = _cases[case_id]
    if case.benchmark_type not in _DETERMINISTIC_TYPES:
        cassette_path = CASSETTE_DIR / cassette_filename(case_id)
        if not cassette_path.exists() and not os.environ.get("OPENAI_API_KEY"):
            pytest.skip(f"no cassette for {cassette_path.name!r} and OPENAI_API_KEY is unset")

    result = await rr.run_reasoning_case(case, DEFAULT_MODEL)

    if case.benchmark_type not in _DETERMINISTIC_TYPES:
        import openai
        judge_client = openai.AsyncOpenAI()
    else:
        judge_client = None

    score = await scoring.score_reasoning_case(case, result, judge_client, DEFAULT_MODEL)
    _collected_scores.append(score)
    _collected_results.append(result)
